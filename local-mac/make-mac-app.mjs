// Best effort: render the icon with macOS's own tools. The app works without it.
function buildIcon(resources){
 const work=mkdtempSync(join(tmpdir(),'my-library-icon-'));
 try{
  const svg=join(work,'icon.svg');
  writeFileSync(svg,ICON_SVG);
  spawnSync('/usr/bin/qlmanage',['-t','-s','1024','-o',work,svg],{stdio:'ignore'});
  const png=join(work,'icon.svg.png');
  if(!existsSync(png))return false;
  const set=join(work,'AppIcon.iconset');mkdirSync(set);
  for(const size of [16,32,128,256,512]){
   spawnSync('/usr/bin/sips',['-z',String(size),String(size),png,'--out',join(set,`icon_${size}x${size}.png`)],{stdio:'ignore'});
   spawnSync('/usr/bin/sips',['-z',String(size*2),String(size*2),png,'--out',join(set,`icon_${size}x${size}@2x.png`)],{stdio:'ignore'});
  }
  const r=spawnSync('/usr/bin/iconutil',['-c','icns',set,'-o',join(resources,'AppIcon.icns')],{stdio:'ignore'});
  return r.status===0&&existsSync(join(resources,'AppIcon.icns'));
 }catch{return false;}
 finally{rmSync(work,{recursive:true,force:true});}
}

function buildApp(out,name,exe,id,script){
 const app=join(out,name+'.app');
 rmSync(app,{recursive:true,force:true});
 const macos=join(app,'Contents','MacOS'),resources=join(app,'Contents','Resources');
 mkdirSync(macos,{recursive:true});mkdirSync(resources,{recursive:true});
 writeFileSync(join(macos,exe),script);
 chmodSync(join(macos,exe),0o755);
 const icon=process.platform==='darwin'&&buildIcon(resources);
 writeFileSync(join(app,'Contents','Info.plist'),plist(name,exe,id,icon));
 return app;
}

export function makeApps({root,out,desktop,nodeDir}){
 const open=buildApp(out,'My Library','MyLibrary','local.my-library.launcher',launcherScript(root,nodeDir));
 const stop=buildApp(out,'Stop My Library','StopMyLibrary','local.my-library.stop',stopScript(root));
 let shortcut=null;
 if(desktop){
  shortcut=join(desktop,'My Library');
  try{if(lstatSync(shortcut).isSymbolicLink())unlinkSync(shortcut);}catch{}
  if(!existsSync(shortcut))symlinkSync(open,shortcut);
  else shortcut=null;
 }
 return {open,stop,shortcut};
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const args=process.argv.slice(2);
 const value=flag=>{const i=args.indexOf(flag);return i>=0?args[i+1]:null;};
 const root=resolve(value('--root')||join(here,'..'));
 const out=resolve(value('--out')||join(homedir(),'Applications'));
 const desktop=args.includes('--no-desktop')?null:join(homedir(),'Desktop');
 const nodeDir=dirname(process.execPath);
 if(!existsSync(join(root,'local-mac','local.mjs')))
  throw Error('Not a my-library folder: '+root);
 mkdirSync(out,{recursive:true});
 const made=makeApps({root,out,desktop,nodeDir});
 console.log('Created '+made.open);
 console.log('Created '+made.stop);
 console.log(made.shortcut?'Desktop shortcut: '+made.shortcut:
  (desktop?'A Desktop item named "My Library" already exists; left it alone.':'No Desktop shortcut requested.'));
 console.log('Library folder: '+root);
}
