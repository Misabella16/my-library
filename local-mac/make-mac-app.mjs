#!/usr/bin/env node
// Builds "My Library.app" and "Stop My Library.app" for the Mac-local edition.
//
//   npm run local:app                      apps in ~/Applications + Desktop shortcut
//   node local-mac/make-mac-app.mjs --root /path/to/my-library --out /some/dir --no-desktop
//
// The apps are tiny shell launchers: they start the loopback-only local site
// (npm run local:start) in the background if it isn't running, then open it in
// the default browser. Nothing is installed system-wide and no Cloudflare
// command is ever run. Re-run this after moving the my-library folder.
import {mkdirSync,writeFileSync,chmodSync,existsSync,rmSync,symlinkSync,lstatSync,unlinkSync,mkdtempSync} from 'node:fs';
import {join,resolve,dirname} from 'node:path';
import {homedir,tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const here=dirname(fileURLToPath(import.meta.url));
const PORT=8788;
const shellQuote=s=>"'"+String(s).replace(/'/g,"'\\''")+"'";
const xml=s=>String(s).replace(/[&<>]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;'}[c]));

export function launcherScript(root,nodeDir){
 return `#!/bin/bash
# My Library launcher (generated by local-mac/make-mac-app.mjs).
# On Apple-chip Macs, run natively: a universal Node started under Rosetta
# would look for the Intel build of Cloudflare's local runtime and fail.
if [ "$(/usr/sbin/sysctl -n hw.optional.arm64 2>/dev/null)" = "1" ] && [ "$(/usr/bin/uname -m)" != "arm64" ]; then
  exec /usr/bin/arch -arm64 /bin/bash "$0" "$@"
fi
LIB=\${MY_LIBRARY_ROOT:-${shellQuote(root)}}
export PATH=${shellQuote(nodeDir)}:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin
URL="http://127.0.0.1:${PORT}/"
STATE="$LIB/.my-library-local"
LOG="$STATE/server.log"
alert(){ /usr/bin/osascript -e 'on run argv' -e 'display alert "My Library" message (item 1 of argv) as critical' -e 'end run' "$1" >/dev/null 2>&1; }
running(){ /usr/bin/nc -z 127.0.0.1 ${PORT} >/dev/null 2>&1; }
if [ ! -f "$LIB/local-mac/local.mjs" ]; then
  alert "Can't find your library folder at $LIB. If you moved it, open Terminal in the new my-library folder and run: npm run local:app"
  exit 1
fi
if ! command -v node >/dev/null 2>&1; then
  alert "Node.js isn't installed. Install the LTS version from nodejs.org, then open My Library again."
  exit 1
fi
if ! running; then
  mkdir -p "$STATE"
  cd "$LIB" || exit 1
  if [ ! -x "$LIB/node_modules/.bin/wrangler" ]; then
    npm install >>"$LOG" 2>&1 || { alert "Installing My Library's tools failed. Details: $LOG"; exit 1; }
  fi
  if [ ! -d "$STATE/state/v3/d1" ]; then
    npm run local:setup >>"$LOG" 2>&1 || { alert "Setting up the local library failed. Details: $LOG"; exit 1; }
  fi
  echo "---- started $(date)" >>"$LOG"
  nohup npm run local:start >>"$LOG" 2>&1 </dev/null &
  for _ in $(seq 1 120); do running && break; sleep 0.5; done
  if ! running; then
    alert "My Library didn't start. Details are in $LOG"
    exit 1
  fi
fi
/usr/bin/open "$URL"
`;
}

export function stopScript(root){
 return `#!/bin/bash
# Stops the My Library local server (generated by local-mac/make-mac-app.mjs).
LIB=\${MY_LIBRARY_ROOT:-${shellQuote(root)}}
/usr/bin/pkill -f -- "--persist-to $LIB/.my-library-local/state" >/dev/null 2>&1
for _ in $(seq 1 20); do /usr/bin/nc -z 127.0.0.1 ${PORT} >/dev/null 2>&1 || break; sleep 0.25; done
if /usr/bin/nc -z 127.0.0.1 ${PORT} >/dev/null 2>&1; then
  /usr/bin/osascript -e 'display alert "My Library" message "The library server is still running. Restarting the Mac will stop it."' >/dev/null 2>&1
else
  /usr/bin/osascript -e 'display notification "Your library server is stopped. Your books are saved." with title "My Library"' >/dev/null 2>&1
fi
`;
}

